const assert = require('node:assert/strict');
const {chromium} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const base = process.env.TEST_BASE || 'http://127.0.0.1:4186';
(async()=>{
  const browser=await chromium.launch({channel:'chrome',headless:true});
  try {
    const a=await browser.newContext({serviceWorkers:'block'}),b=await browser.newContext({serviceWorkers:'block'});
    const sender=await a.newPage(),receiver=await b.newPage();
    const url=base+'/?cloud=1&open=chat&room=QA'+require('node:crypto').randomBytes(18).toString('hex');
    await sender.goto(url);
    await sender.waitForSelector('.chat-compose textarea');
    await sender.locator('textarea').fill('連線前的測試文字');
    await sender.waitForTimeout(1100);
    await sender.evaluate(()=>addChatMessage({id:'old-history-test',deviceId:chat.deviceId,deviceName:'筆電',createdAt:new Date().toISOString(),content:'舊版留下的紀錄'}));
    await receiver.goto(base+'/?cloud=1&open=chat');
    await receiver.waitForSelector('.chat-compose textarea');
    await sender.locator('.chat-pairing summary').click();
    await receiver.locator('.chat-pairing summary').click();
    const pairingCode=await sender.getByLabel('本機完整配對碼',{exact:true}).inputValue();
    assert.notEqual(await receiver.getByLabel('本機完整配對碼',{exact:true}).inputValue(),pairingCode);
    await receiver.getByLabel('另一台的配對碼或連線網址',{exact:true}).fill(base+'/');
    await receiver.getByRole('button',{name:'加入同一房間',exact:true}).click();
    await receiver.getByText('請貼上完整配對碼',{exact:false}).waitFor();
    await receiver.getByLabel('另一台的配對碼或連線網址',{exact:true}).fill(pairingCode);
    await receiver.getByRole('button',{name:'加入同一房間',exact:true}).click();
    await receiver.getByText('連線前的測試文字',{exact:true}).waitFor({timeout:45000});
    await receiver.getByText('舊版留下的紀錄',{exact:true}).waitFor({timeout:15000});
    await sender.waitForFunction(()=>chat.outbox.length===0,{},{timeout:15000});
    await b.setOffline(true);
    await sender.locator('textarea').fill('恢復網路後補傳');
    await sender.waitForTimeout(1100);
    await b.setOffline(false);
    await receiver.reload();
    await receiver.getByText('恢復網路後補傳',{exact:true}).waitFor({timeout:45000});
    await sender.waitForFunction(()=>chat.outbox.length===0,{},{timeout:15000});
    assert.equal(await receiver.getByText('恢復網路後補傳',{exact:true}).count(),1);
    const c=await browser.newContext({serviceWorkers:'block'});const late=await c.newPage();await late.goto(url);
    await late.getByText('連線前的測試文字',{exact:true}).waitFor({timeout:45000});
    await late.getByText('舊版留下的紀錄',{exact:true}).waitFor({timeout:15000});
    console.log('PASS: different initial rooms, invalid-link guidance, pairing, queued delivery, history synchronization, late joining, reconnect and acknowledgment');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
